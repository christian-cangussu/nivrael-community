async def run_dungeon_quest_seeds(session):
    """Upsert dungeon quests catalog."""
    for data in DUNGEON_QUEST_SEEDS:
        q_id = data["id"]
        quest = await session.get(DungeonQuestCatalog, q_id)
        if not quest:
            quest = DungeonQuestCatalog(id=q_id)
            session.add(quest)

        quest.dungeon_id = data["dungeon_id"]
        quest.name = data["name"]
        quest.description_key = data["description_key"]
        quest.story_intro_key = data["story_intro_key"]
        quest.story_complete_key = data["story_complete_key"]
        quest.objective_type = data["objective_type"]
        quest.objective_target = data["objective_target"]
        quest.objective_count = data["objective_count"]
        quest.reward_rep = data["reward_rep"]
        quest.reward_stones = data["reward_stones"]
        quest.reward_items = data["reward_items"]
        quest.cooldown_hours = data["cooldown_hours"]
        quest.min_difficulty = data["min_difficulty"]
        quest.emoji = data["emoji"]

        flag_modified(quest, "reward_items")

    await session.commit()
    logger.info(f"Seeded {len(DUNGEON_QUEST_SEEDS)} dungeon quests.")
